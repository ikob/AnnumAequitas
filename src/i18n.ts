export const defaultLocale: Locale = 'en';
export function parseLocale(value: unknown): Locale { return value === 'ja' ? 'ja' : defaultLocale; }
export function translate(locale: Locale, key: MessageKey, params: Params = {}): string {
  const message = (locale === 'ja' ? ja : en)[key] ?? en[key];
  return message.replace(/\{(\w+)\}/g, (token, name: string) => String(params[name] ?? token));
}
export function translateIssue(locale: Locale, code: string): string {
  if (code.startsWith('date:')) return translate(locale, 'issue.date', { field: code.slice(5) });
  if (code.startsWith('number:')) return translate(locale, 'issue.number', { field: code.slice(7) });
  const keys: Record<string, MessageKey> = {
    vest: 'issue.vest', sale: 'issue.sale', other: 'issue.other', tax: 'issue.tax', settlement: 'issue.settlement', 'cash-amount': 'issue.cash-amount', 'cash-sign': 'issue.cash-sign',
  };
  return translate(locale, keys[code] ?? 'issue.unknown');
}
